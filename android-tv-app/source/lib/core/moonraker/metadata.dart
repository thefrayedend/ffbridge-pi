// G-code / 3MF metadata + thumbnail extraction (Moonraker-compatible fields).
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import '../util/zip.dart';

class ExtractedThumb {
  final int width, height;
  final Uint8List png;
  ExtractedThumb(this.width, this.height, this.png);
}

class GcodeMetadata {
  final Map<String, dynamic> meta = {};
  final List<ExtractedThumb> thumbs = [];
  int toolCount = 0;
}

double? _num(String? s) => s == null ? null : double.tryParse(s.trim().split(RegExp(r'[,;\s]')).first);

double? _parseDuration(String s) {
  // "1d 2h 3m 4s" / "2h 3m" / "45m 10s"
  var total = 0.0;
  var any = false;
  for (final m in RegExp(r'(\d+(?:\.\d+)?)\s*([dhms])').allMatches(s)) {
    final v = double.parse(m.group(1)!);
    any = true;
    switch (m.group(2)) {
      case 'd':
        total += v * 86400;
      case 'h':
        total += v * 3600;
      case 'm':
        total += v * 60;
      case 's':
        total += v;
    }
  }
  return any ? total : null;
}

/// Parses slicer comments from the first/last 256 KB of a G-code file.
Future<GcodeMetadata> extractGcodeMetadata(File f) async {
  final md = GcodeMetadata();
  final len = await f.length();
  final raf = await f.open();
  const window = 262144;
  final head = utf8.decode(await raf.read(len < window ? len : window), allowMalformed: true);
  String tail = '';
  if (len > window) {
    await raf.setPosition(len > window * 2 ? len - window : window);
    tail = utf8.decode(await raf.read(window), allowMalformed: true);
  }
  await raf.close();
  final text = '$head\n$tail';
  final kv = <String, String>{};
  for (final line in LineSplitter.split(text)) {
    if (!line.startsWith(';')) continue;
    final body = line.substring(1).trim();
    final i = body.indexOf(RegExp(r'[=:]'));
    if (i <= 0) continue;
    kv.putIfAbsent(body.substring(0, i).trim().toLowerCase(), () => body.substring(i + 1).trim());
  }
  final m = md.meta;
  // slicer
  final gen = RegExp(r'generated by\s+([A-Za-z\-]+(?:Slicer)?)[ \-]*([0-9][^\s]*)?', caseSensitive: false).firstMatch(head);
  if (gen != null) {
    m['slicer'] = gen.group(1);
    if (gen.group(2) != null) m['slicer_version'] = gen.group(2);
  }
  double? first(List<String> keys) {
    for (final k in keys) {
      final v = _num(kv[k]);
      if (v != null) return v;
    }
    return null;
  }

  String? firstStr(List<String> keys) {
    for (final k in keys) {
      if (kv[k] != null && kv[k]!.isNotEmpty) return kv[k];
    }
    return null;
  }

  for (final k in kv.keys) {
    if (k.startsWith('estimated printing time') || k == 'total estimated time' || k == 'model printing time') {
      final d = _parseDuration(kv[k]!);
      if (d != null && m['estimated_time'] == null) m['estimated_time'] = d.roundToDouble();
    }
  }
  m['estimated_time'] ??= first(['estimated_time', 'print_time', 'time']);
  final lh = first(['layer_height']);
  if (lh != null) m['layer_height'] = lh;
  final flh = first(['first_layer_height', 'initial_layer_print_height']);
  if (flh != null) m['first_layer_height'] = flh;
  final oh = first(['max_z_height', 'max_layer_z', 'object_height']);
  if (oh != null) m['object_height'] = oh;
  final lc = first(['total layer number', 'total_layer_count', 'layer_count', 'total layers count']);
  if (lc != null) m['layer_count'] = lc.toInt();
  final nd = first(['nozzle_diameter']);
  if (nd != null) m['nozzle_diameter'] = nd;
  final fmm = firstStr(['filament used [mm]', 'total filament used [mm]']);
  if (fmm != null) {
    m['filament_total'] = fmm.split(RegExp(r'[,;]')).map((e) => double.tryParse(e.trim()) ?? 0).fold<double>(0, (a, b) => a + b);
  }
  final fg = firstStr(['total filament weight [g]', 'filament used [g]', 'total filament used [g]']);
  if (fg != null) {
    m['filament_weight_total'] = fg.split(RegExp(r'[,;]')).map((e) => double.tryParse(e.trim()) ?? 0).fold<double>(0, (a, b) => a + b);
  }
  final ft = firstStr(['filament_type']);
  if (ft != null) m['filament_type'] = ft;
  final fname = firstStr(['filament_settings_id', 'filament_name']);
  if (fname != null) m['filament_name'] = fname.replaceAll('"', '');
  final fe = first(['first_layer_temperature', 'nozzle_temperature_initial_layer', 'first_layer_extr_temp']);
  if (fe != null) m['first_layer_extr_temp'] = fe;
  final fb = first(['first_layer_bed_temperature', 'hot_plate_temp_initial_layer', 'bed_temperature_initial_layer_single', 'textured_plate_temp_initial_layer']);
  if (fb != null) m['first_layer_bed_temp'] = fb;
  final colors = firstStr(['filament_colour', 'filament_color', 'extruder_colour']);
  if (colors != null) m['filament_colors'] = colors.split(RegExp(r'[;,]')).map((e) => e.trim()).where((e) => e.isNotEmpty).toList();
  // tools used
  final tools = <int>{};
  for (final t in RegExp(r'^T(\d)\s*$', multiLine: true).allMatches(text)) {
    tools.add(int.parse(t.group(1)!));
  }
  md.toolCount = tools.length;
  if (tools.length > 1) m['filament_change_count'] = tools.length;

  // thumbnails: "; thumbnail begin 300x300 12345" (also thumbnail_PNG / thumbnail_JPG)
  final tre = RegExp(r'; thumbnail(?:_(PNG|JPG|QOI))? begin (\d+)[x ](\d+)[^\n]*\n([\s\S]*?); thumbnail(?:_\w+)? end', caseSensitive: false);
  for (final t in tre.allMatches(head)) {
    final fmt = (t.group(1) ?? 'PNG').toUpperCase();
    if (fmt == 'QOI') continue;
    final b64 = t.group(4)!.split('\n').map((l) => l.replaceFirst(RegExp(r'^;\s?'), '').trim()).join();
    try {
      md.thumbs.add(ExtractedThumb(int.parse(t.group(2)!), int.parse(t.group(3)!), base64.decode(b64)));
    } catch (_) {}
  }
  return md;
}

/// 3MF (zip) metadata: plate thumbnail, slicer info and filament list.
Future<GcodeMetadata> extract3mfMetadata(File f) async {
  final md = GcodeMetadata();
  final zip = ZipReader.tryFile(f.path);
  if (zip == null) return md;
  final thumb = zip.find((n) => RegExp(r'Metadata/plate_\d+\.png$').hasMatch(n) && !n.contains('small')) ??
      zip.find((n) => n.toLowerCase().endsWith('thumbnail.png') || n.toLowerCase().endsWith('.png'));
  if (thumb != null) {
    final png = zip.read(thumb);
    var w = 0, h = 0;
    if (png.length > 24) {
      final bd = ByteData.sublistView(png);
      w = bd.getUint32(16);
      h = bd.getUint32(20);
    }
    md.thumbs.add(ExtractedThumb(w, h, png));
  }
  final sliceInfo = zip.find((n) => n.endsWith('Metadata/slice_info.config'));
  if (sliceInfo != null) {
    final x = utf8.decode(zip.read(sliceInfo), allowMalformed: true);
    final pred = RegExp(r'key="prediction" value="(\d+)"').firstMatch(x);
    if (pred != null) md.meta['estimated_time'] = double.parse(pred.group(1)!);
    final weight = RegExp(r'key="weight" value="([\d.]+)"').firstMatch(x);
    if (weight != null) md.meta['filament_weight_total'] = double.parse(weight.group(1)!);
    final fils = RegExp(r'<filament id="(\d+)"[^>]*type="([^"]*)"[^>]*color="([^"]*)"[^>]*used_m="([\d.]+)"').allMatches(x).toList();
    if (fils.isNotEmpty) {
      md.toolCount = fils.length;
      md.meta['filament_type'] = fils.map((e) => e.group(2)).join(';');
      md.meta['filament_colors'] = fils.map((e) => e.group(3)).toList();
      md.meta['filament_total'] = fils.fold<double>(0, (a, e) => a + double.parse(e.group(4)!) * 1000);
      md.meta['mmu_filaments'] = [for (final e in fils) {'id': int.parse(e.group(1)!), 'type': e.group(2), 'color': e.group(3)}];
    }
  }
  final model = zip.find((n) => n.endsWith('Metadata/model_settings.config'));
  if (model != null) md.meta['slicer'] = 'OrcaSlicer';
  return md;
}
